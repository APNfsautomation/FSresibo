// Builds the static UAT site (Issue #49) from the CURRENT git checkout into an output folder. Nothing is published by this script.
//
//   node tools/build-uat.mjs --out <dir> --key <UAT browser-safe key>      (or UAT_SUPABASE_KEY in the environment)
//
// The build copies the tracked runtime files only (no tests, docs, migrations, workflows or audit manifest), points config/supabase.js at the UAT Supabase project,
// marks the visible version as a UAT build of the exact commit, writes BUILD-INFO.json, and then verifies its own output:
//   - the production Supabase project reference appears nowhere;
//   - the key is a browser-safe one (a publishable `sb_publishable_` key, or a legacy JWT whose role is `anon`); secret / service-role keys are refused;
//   - a legacy JWT key must belong to the UAT project reference.
// All paths in the app are relative, so the site works under the GitHub Pages base path /FSresibo-UAT/.
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

export const uatProjectRef = 'wnudewolpouussjtblis';
export const productionProjectRef = 'ilinpznoawvsplkhjaqr';
export const uatUrl = `https://${uatProjectRef}.supabase.co`;
export const uatBasePath = '/FSresibo-UAT/';
const runtimeFiles = ['index.html', 'app.js', 'styles.css', 'auth.css', 'assets', 'config', 'domain', 'services', 'ui', 'vendor'];
const excluded = new Set(['vendor/dependency-manifest.json']);

// Throws unless the key is browser-safe for the UAT project.
export function assertBrowserSafeKey(key) {
  const value = String(key ?? '').trim();
  if (!value) throw new Error('A UAT publishable key is required.');
  if (/^sb_secret_/i.test(value) || /service[_-]?role/i.test(value)) throw new Error('Refusing a secret or service-role key: only a browser-safe key may be published.');
  if (/^sb_publishable_/i.test(value)) return value;
  const parts = value.split('.');
  if (parts.length !== 3) throw new Error('Unrecognised key format: expected an sb_publishable_ key or a legacy anon JWT.');
  let payload; try { payload = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')); } catch { throw new Error('The key is not a readable JWT.'); }
  if (payload.role !== 'anon') throw new Error(`Refusing a key with role "${payload.role}": only the anon/publishable role may be published.`);
  if (payload.ref !== uatProjectRef) throw new Error(`The key belongs to project "${payload.ref}", not the UAT project.`);
  return value;
}

export function uatConfigSource(key) {
  return `// UAT build (Issue #49): the isolated UAT Supabase project only. Generated by tools/build-uat.mjs; never contains production or privileged keys.\nexport const supabaseConfig = Object.freeze({\n  url: '${uatUrl}',\n  anonKey: '${key}'\n});\n\nlet client;\n\nexport function isSupabaseConfigured() {\n  return supabaseConfig.url !== 'YOUR_SUPABASE_URL' && supabaseConfig.anonKey !== 'YOUR_SUPABASE_ANON_KEY';\n}\n`;
}

const walk = directory => readdirSync(directory).flatMap(name => { const path = join(directory, name); return statSync(path).isDirectory() ? walk(path) : [path]; });

export function buildUat({ out, key, commit, now = new Date() }) {
  const safeKey = assertBrowserSafeKey(key);
  rmSync(out, { recursive: true, force: true }); mkdirSync(out, { recursive: true });
  for (const entry of runtimeFiles) cpSync(entry, join(out, entry), { recursive: true, filter: source => !excluded.has(source.replaceAll('\\', '/')) });
  // config/supabase.js keeps its client factory; only the two values change.
  const original = readFileSync('config/supabase.js', 'utf8');
  const factory = original.slice(original.indexOf('let client;'));
  writeFileSync(join(out, 'config/supabase.js'), uatConfigSource(safeKey).replace(/let client;[\s\S]*$/, factory));
  const short = commit.slice(0, 7);
  const metadata = readFileSync('config/appMetadata.js', 'utf8').replace(/version: '([^']+)'/, (_, version) => `version: '${version}-uat+${short}'`);
  writeFileSync(join(out, 'config/appMetadata.js'), metadata);
  writeFileSync(join(out, '.nojekyll'), '');
  writeFileSync(join(out, 'BUILD-INFO.json'), `${JSON.stringify({ environment: 'UAT', sourceRepository: 'APNfsautomation/FSresibo', sourceCommit: commit, builtAt: now.toISOString(), supabaseProject: uatProjectRef, basePath: uatBasePath }, null, 2)}\n`);
  // Self-verification of the output.
  const files = walk(out); const problems = [];
  for (const file of files) {
    if (/\.(png|ico)$/i.test(file)) continue;
    const text = readFileSync(file, 'utf8');
    if (text.includes(productionProjectRef)) problems.push(`${relative(out, file)} mentions the production project`);
    if (/service_role|sb_secret_/i.test(text) && !/vendor\//.test(relative(out, file).replaceAll('\\', '/'))) problems.push(`${relative(out, file)} mentions a privileged key`);
  }
  const config = readFileSync(join(out, 'config/supabase.js'), 'utf8');
  if (!config.includes(uatUrl)) problems.push('config/supabase.js does not point at the UAT project');
  if (/(^|[^/])\/FSresibo\//.test(readFileSync(join(out, 'index.html'), 'utf8'))) problems.push('index.html contains an absolute production path');
  if (problems.length) throw new Error(`UAT build verification failed:\n- ${problems.join('\n- ')}`);
  return { files: files.length, commit };
}

if (import.meta.url === `file:///${process.argv[1]?.replaceAll('\\', '/')}`) {
  const args = process.argv.slice(2); const option = name => { const index = args.indexOf(`--${name}`); return index >= 0 ? args[index + 1] : undefined; };
  const out = option('out'); const key = option('key') ?? process.env.UAT_SUPABASE_KEY;
  if (!out) { console.error('usage: node tools/build-uat.mjs --out <dir> --key <key>'); process.exit(2); }
  const dirty = execFileSync('git', ['status', '--porcelain'], { encoding: 'utf8' }).trim();
  if (dirty) { console.error('Refusing to build from a dirty working tree.'); process.exit(1); }
  const commit = execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  try { console.log(JSON.stringify(buildUat({ out, key, commit }))); } catch (error) { console.error(error.message); process.exit(1); }
}
